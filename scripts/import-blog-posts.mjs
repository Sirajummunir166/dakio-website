// One-off importer: copies the .mdx posts from dakio-landing with their YAML
// frontmatter stripped into content/blog/, and generates lib/blog-meta.js from
// that frontmatter (we compile MDX with mdxRs, which has no remark-frontmatter
// stage — metadata lives in JS instead).
// Run: node scripts/import-blog-posts.mjs [source-dir]

import { readFileSync, writeFileSync, readdirSync, mkdirSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join, basename } from "node:path";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const src = process.argv[2] || "D:/Dakio Apps/dakio-landing/src/content/blog";
const outContent = join(root, "content", "blog");
mkdirSync(outContent, { recursive: true });

const metas = [];

for (const file of readdirSync(src).filter(f => f.endsWith(".mdx"))) {
  const raw = readFileSync(join(src, file), "utf8");
  const m = raw.match(/^---\r?\n([\s\S]*?)\r?\n---\r?\n?/);
  if (!m) throw new Error(`no frontmatter in ${file}`);
  const meta = {};
  for (const line of m[1].split(/\r?\n/)) {
    const kv = line.match(/^(\w+):\s*(.*)$/);
    if (!kv) continue;
    let v = kv[2].trim().replace(/^"(.*)"$/, "$1");
    if (v === "true") v = true;
    else if (v === "false") v = false;
    else if (/^\d+$/.test(v)) v = Number(v);
    meta[kv[1]] = v;
  }
  metas.push(meta);
  writeFileSync(join(outContent, file), raw.slice(m[0].length));
  console.log("post:", basename(file), "→", meta.slug);
}

metas.sort((a, b) => (a.date < b.date ? 1 : -1));

const js = `// GENERATED by scripts/import-blog-posts.mjs — frontmatter of content/blog/*.mdx.
// Edit the .mdx source in dakio-landing and re-run the script, or edit here directly.

export const POST_META = ${JSON.stringify(metas, null, 2)};
`;
writeFileSync(join(root, "lib", "blog-meta.js"), js);
console.log(`wrote lib/blog-meta.js (${metas.length} posts)`);
